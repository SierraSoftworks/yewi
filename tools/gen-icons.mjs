#!/usr/bin/env node
// Regenerates yewi/src/icons/lucide.rs from the `lucide-static` npm package.
//
//   npm pack lucide-static@<version> && tar xzf lucide-static-*.tgz
//   node tools/gen-icons.mjs package
//
// Each icon becomes one path string: shapes (circle, rect, line, ...) are
// converted to path commands and joined, so an icon renders as a single
// <path> element.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = process.argv[2];
if (!pkg) {
  console.error("usage: gen-icons.mjs <path to unpacked lucide-static package>");
  process.exit(1);
}

// Read the SVG files rather than icon-nodes.json, which omits aliased names.
const nodes = {};
for (const file of readdirSync(join(pkg, "icons")).filter((f) => f.endsWith(".svg"))) {
  const svg = readFileSync(join(pkg, "icons", file), "utf8");
  const body = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1);
  nodes[file.slice(0, -4)] = [...body.matchAll(/<([a-z]+)\s+([^>]*?)\s*\/>/g)].map(([, tag, attrs]) => [
    tag,
    Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v])),
  ]);
}
const version = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8")).version;
const n = (v) => +(+v).toFixed(3);

function toPath([tag, a]) {
  switch (tag) {
    case "path":
      return absoluteStart(a.d);
    case "circle":
    case "ellipse": {
      const rx = n(a.r ?? a.rx), ry = n(a.r ?? a.ry), cx = n(a.cx), cy = n(a.cy);
      return `M${n(cx - rx)} ${cy}a${rx} ${ry} 0 1 0 ${n(rx * 2)} 0a${rx} ${ry} 0 1 0 ${n(-rx * 2)} 0`;
    }
    case "rect": {
      const x = n(a.x ?? 0), y = n(a.y ?? 0), w = n(a.width), h = n(a.height);
      const rx = Math.min(n(a.rx ?? a.ry ?? 0), w / 2), ry = Math.min(n(a.ry ?? a.rx ?? 0), h / 2);
      if (!rx && !ry) return `M${x} ${y}h${w}v${h}h${-w}z`;
      const arc = (dx, dy) => `a${rx} ${ry} 0 0 1 ${dx} ${dy}`;
      return `M${n(x + rx)} ${y}h${n(w - 2 * rx)}${arc(rx, ry)}v${n(h - 2 * ry)}${arc(-rx, ry)}h${n(2 * rx - w)}${arc(-rx, -ry)}v${n(2 * ry - h)}${arc(rx, -ry)}z`;
    }
    case "line":
      return `M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`;
    case "polyline":
    case "polygon": {
      const pts = a.points.trim().split(/[\s,]+/).map(n);
      let d = `M${pts[0]} ${pts[1]}`;
      for (let i = 2; i < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`;
      return tag === "polygon" ? d + "z" : d;
    }
    default:
      throw new Error(`unsupported element <${tag}>`);
  }
}

// A leading relative moveto is absolute on its own but relative once paths are
// joined, so rewrite `m x y <implicit linetos>` as `M x y l <linetos>`.
function absoluteStart(d) {
  const num = "[-+]?(?:\\d*\\.\\d+|\\d+\\.?)(?:e[-+]?\\d+)?";
  const m = d.match(new RegExp(`^\\s*m\\s*(${num})[\\s,]*(${num})([\\s,]*)`, "i"));
  if (!m || d.trimStart()[0] !== "m") return d.trim();
  const rest = d.slice(m[0].length);
  return `M${m[1]} ${m[2]}${/^[-+.\d]/.test(rest) ? "l" : ""}${rest}`;
}

const ident = (name) => {
  const id = name.toUpperCase().replace(/-/g, "_");
  return /^[0-9]/.test(id) ? `_${id}` : id;
};

const names = Object.keys(nodes).sort();
let out = `// @generated by tools/gen-icons.mjs from lucide-static ${version}. Do not edit.
//
// Icon paths are derived from Lucide (https://lucide.dev), ISC License,
// Copyright (c) Lucide Contributors; portions derived from Feather, MIT
// License, Copyright (c) 2013-2023 Cole Bemis. See LICENSE-THIRD-PARTY.

use super::IconData;

`;
for (const name of names) {
  const d = nodes[name].map(toPath).join("");
  out += `/// \`${name}\`\npub const ${ident(name)}: IconData = IconData::new(${JSON.stringify(d)});\n`;
}
out += `\n/// Every bundled icon as \`(name, icon)\`, for galleries and pickers. Referencing\n/// this keeps every icon in the binary, so apps should not.\npub const ALL: &[(&str, IconData)] = &[\n`;
for (const name of names) out += `    (${JSON.stringify(name)}, ${ident(name)}),\n`;
out += "];\n";

const target = join(dirname(fileURLToPath(import.meta.url)), "../yewi/src/icons/lucide.rs");
writeFileSync(target, out);
console.log(`wrote ${names.length} icons from lucide-static ${version}`);
